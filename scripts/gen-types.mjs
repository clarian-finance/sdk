// Generates src/schema.ts from openapi.json (components.schemas). Run: npm run gen
import { readFileSync, writeFileSync } from "node:fs";

const spec = JSON.parse(readFileSync(new URL("../openapi.json", import.meta.url), "utf8"));
const schemas = spec.components.schemas;
// "Error" would shadow the global Error class in consumers.
const rename = (n) => (n === "Error" ? "ApiErrorBody" : n);
const doc = (text, indent) => (text ? `${indent}/** ${text.replace(/\*\//g, "").replace(/\s+/g, " ")} */\n` : "");

const ts = (s, indent = "", isRequest = false) => {
  if (!s || Object.keys(s).length === 0) return "unknown";
  if (s.$ref) return rename(s.$ref.split("/").pop());
  const alts = s.oneOf ?? s.anyOf;
  if (alts) return [...new Set(alts.map((a) => ts(a, indent, isRequest)))].join(" | ");
  if (s.allOf) return s.allOf.map((a) => ts(a, indent, isRequest)).join(" & ");
  const nullable = s.nullable || (Array.isArray(s.type) && s.type.includes("null"));
  const type = Array.isArray(s.type) ? s.type.find((t) => t !== "null") : s.type;
  const base = (() => {
    if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(" | ");
    if (type === "string") return "string";
    if (type === "integer" || type === "number") return "number";
    if (type === "boolean") return "boolean";
    if (type === "array") return `ReadonlyArray<${ts(s.items, indent)}>`;
    if (type !== "object" && !s.properties) return "unknown";
    if (!s.properties) return "Readonly<Record<string, unknown>>";
    const req = new Set(s.required ?? []);
    const lines = Object.entries(s.properties).map(([k, v]) => {
      const key = /^[a-z_][a-z0-9_]*$/i.test(k) ? k : JSON.stringify(k);
      // Request amounts also accept bigint; the client serializes it as a string.
      const t = ts(v, indent + "  ", isRequest) + (isRequest && k.endsWith("_minor") ? " | bigint" : "");
      return `${doc(v.description, indent + "  ")}${indent}  readonly ${key}${req.has(k) ? "" : "?"}: ${t};`;
    });
    return `{\n${lines.join("\n")}\n${indent}}`;
  })();
  return nullable ? `${base} | null` : base;
};

const out = Object.entries(schemas).map(([raw, s]) => {
  const name = rename(raw);
  const body = ts(s, "", raw.endsWith("Request"));
  return body.startsWith("{")
    ? `${doc(s.description, "")}export interface ${name} ${body}`
    : `${doc(s.description, "")}export type ${name} = ${body};`;
});
writeFileSync(
  new URL("../src/schema.ts", import.meta.url),
  `// Generated by scripts/gen-types.mjs from openapi.json. Do not edit.\n\n${out.join("\n\n")}\n`,
);
console.log(`schema.ts: ${out.length} types`);
